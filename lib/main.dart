import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';
import 'package:metra_it_assets/app.dart';

const _webApiKey = String.fromEnvironment('FIREBASE_API_KEY');
const _webAppId = String.fromEnvironment('FIREBASE_APP_ID');
const _webMessagingSenderId = String.fromEnvironment(
  'FIREBASE_MESSAGING_SENDER_ID',
);
const _webProjectId = String.fromEnvironment('FIREBASE_PROJECT_ID');
const _webAuthDomain = String.fromEnvironment('FIREBASE_AUTH_DOMAIN');
const _webStorageBucket = String.fromEnvironment('FIREBASE_STORAGE_BUCKET');

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  try {
    if (kIsWeb) {
      final missing = <String>[
        if (_webApiKey.isEmpty) 'FIREBASE_API_KEY',
        if (_webAppId.isEmpty) 'FIREBASE_APP_ID',
        if (_webMessagingSenderId.isEmpty) 'FIREBASE_MESSAGING_SENDER_ID',
        if (_webProjectId.isEmpty) 'FIREBASE_PROJECT_ID',
        if (_webAuthDomain.isEmpty) 'FIREBASE_AUTH_DOMAIN',
        if (_webStorageBucket.isEmpty) 'FIREBASE_STORAGE_BUCKET',
      ];
      if (missing.isNotEmpty) {
        runApp(_FirebaseSetupApp(missing: missing));
        return;
      }
      await Firebase.initializeApp(
        options: FirebaseOptions(
          apiKey: _webApiKey,
          appId: _webAppId,
          messagingSenderId: _webMessagingSenderId,
          projectId: _webProjectId,
          authDomain: _webAuthDomain,
          storageBucket: _webStorageBucket,
        ),
      );
    } else {
      // Native builds use the platform options generated by FlutterFire.
      await Firebase.initializeApp();
    }
    runApp(const MetraItAssetsApp());
  } on FirebaseException catch (error) {
    runApp(_FirebaseSetupApp(errorMessage: error.message ?? error.code));
  } catch (error) {
    runApp(_FirebaseSetupApp(errorMessage: error.toString()));
  }
}

class _FirebaseSetupApp extends StatelessWidget {
  const _FirebaseSetupApp({this.missing = const [], this.errorMessage});
  final List<String> missing;
  final String? errorMessage;

  @override
  Widget build(BuildContext context) => MaterialApp(
        debugShowCheckedModeBanner: false,
        locale: const Locale('ar'),
        home: Directionality(
          textDirection: TextDirection.rtl,
          child: Scaffold(
            body: Center(
              child: ConstrainedBox(
                constraints: const BoxConstraints(maxWidth: 560),
                child: Padding(
                  padding: const EdgeInsets.all(28),
                  child: Card(
                    child: Padding(
                      padding: const EdgeInsets.all(24),
                      child: Column(
                        mainAxisSize: MainAxisSize.min,
                        children: [
                          const Icon(Icons.cloud_off_outlined, size: 52),
                          const SizedBox(height: 16),
                          const Text(
                            'يلزم إعداد Firebase قبل تشغيل النظام',
                            style: TextStyle(
                              fontSize: 20,
                              fontWeight: FontWeight.bold,
                            ),
                            textAlign: TextAlign.center,
                          ),
                          const SizedBox(height: 10),
                          const Text(
                            'لم يتم الاتصال بقاعدة بيانات الأصول. '
                            'أكمل إعداد Firebase الخاص بهذا التطبيق فقط.',
                            textAlign: TextAlign.center,
                          ),
                          if (missing.isNotEmpty) ...[
                            const SizedBox(height: 14),
                            const Text('إعدادات الويب الناقصة:'),
                            const SizedBox(height: 6),
                            SelectableText(
                              missing.join('\n'),
                              textAlign: TextAlign.center,
                            ),
                          ],
                          if (errorMessage != null) ...[
                            const SizedBox(height: 12),
                            SelectableText(
                              errorMessage!,
                              textAlign: TextAlign.center,
                            ),
                          ],
                        ],
                      ),
                    ),
                  ),
                ),
              ),
            ),
          ),
        ),
      );
}
